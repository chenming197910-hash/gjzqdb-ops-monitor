-- Additive Oracle migration. Existing CPU history and tenant states are unchanged.
whenever sqlerror exit sql.sqlcode
set define off

begin
 execute immediate q'~create table cluster_sys_cpu_samples (
      id number generated by default on null as identity primary key,
      cluster_id number not null references clusters(id),
      sampled_at timestamp not null,
      cpu_used_cores number,
      cpu_limit_cores number,
      cpu_used_pct number,
      node_count number
    )~';
exception when others then
 if sqlcode != -955 then raise; end if;
end;
/

begin
 execute immediate q'~create index ix_sys_cpu_samples on cluster_sys_cpu_samples(cluster_id,sampled_at)~';
exception when others then
 if sqlcode != -955 then raise; end if;
end;
/
