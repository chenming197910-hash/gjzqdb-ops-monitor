"""Standalone additive SYS CPU migration. Default prints DDL, --apply executes."""
import argparse,json,os
from pathlib import Path
import oracledb

STATEMENTS = ['create table cluster_sys_cpu_samples (\n      id number generated by default on null as identity primary key,\n      cluster_id number not null references clusters(id),\n      sampled_at timestamp not null,\n      cpu_used_cores number,\n      cpu_limit_cores number,\n      cpu_used_pct number,\n      node_count number\n    )', 'create index ix_sys_cpu_samples on cluster_sys_cpu_samples(cluster_id,sampled_at)']


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--apply',action='store_true');args=parser.parse_args()
    if not args.apply:
        print(';\n'.join(STATEMENTS)+';');return
    config_path=Path(os.environ.get('APP_CONFIG',Path(__file__).resolve().parent/'config.json'))
    config=json.loads(config_path.read_text()) if config_path.exists() else {}
    oracle=config.get('oracle',{})
    def value(key,env):return oracle.get(key) or os.environ.get(env,'')
    db=oracledb.connect(user=value('user','ORACLE_USER'),password=value('password','ORACLE_PASSWORD'),dsn=value('dsn','ORACLE_DSN'))
    try:
        with db.cursor() as cur:
            for sql in STATEMENTS:
                try:cur.execute(sql)
                except oracledb.DatabaseError as exc:
                    if getattr(exc.args[0],'code',None)!=955:raise
        print('SYS CPU历史表和索引迁移完成；未修改租户状态或已有历史。')
    finally:db.close()


if __name__=='__main__':main()
